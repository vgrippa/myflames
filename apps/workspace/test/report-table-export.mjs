import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['src/reportTableExport.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const { csvCell, csvReport, htmlReport } = await import('data:text/javascript;base64,' + Buffer.from(built.outputFiles[0].text).toString('base64'));
for (const formula of ['=CMD()', '+1', '-1', '@SUM(A1)', '\t=1', '\r=1', '  =1', '\u0000=1']) assert.ok(csvCell(formula).startsWith('"\''), formula);
assert.equal(csvCell('a,"b"\nc'), '"a,""b""\nc"');
const columns = [{ label: 'Table', value: r => r.name }, { label: 'Rows', value: r => r.n }];
const rows = Array.from({ length: 251 }, (_, n) => ({ name: n === 250 ? '<script>evil()</script>数据库' : `t${n}`, n }));
const csv = csvReport(columns, rows);
assert.ok(csv.startsWith('\uFEFF"Table","Rows"\r\n'));
assert.ok(csv.includes('数据库","250"'));
const html = htmlReport('<img src=x onerror=evil()>', 'Database <test>', columns, rows);
assert.equal((html.match(/<tr>/g) || []).length, 252);
assert.ok(html.includes('&lt;script&gt;evil()&lt;/script&gt;数据库'));
assert.ok(!html.includes('<script>'));
assert.ok(!html.includes('<img'));
assert.ok(html.includes('table-header-group'));
assert.ok(html.includes("default-src 'none'"));
console.log('Report export: formula guards, quoting, HTML escaping, Unicode and all 251 rows passed.');
