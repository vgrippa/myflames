// Writes src/icons.generated.ts from an extracted @hugeicons/core-free-icons@4.3.5
// package (MIT). Usage: node scripts/vendor-hugeicons.mjs /path/to/package
// Only the icons listed below are vendored; the package itself is not a dependency.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// IconName -> Hugeicons export (file name without the Icon suffix).
const MAP = {
  home: "Home01", plan: "Hierarchy", query: "SourceCode", server: "ServerStack01",
  database: "Database", investigation: "Folder01", learn: "BookOpen01", teach: "Mortarboard01",
  connection: "Plug01", key: "Key01", settings: "Settings02", menu: "Menu01",
  more: "MoreHorizontal", import: "Download01", export: "Upload01", compare: "ArrowLeftRight",
  plus: "Add01", close: "Cancel01", chevron: "ArrowRight01", "chevron-down": "ArrowDown01",
  disclosure: "ArrowRight01", back: "ArrowLeft01", search: "Search01", check: "Tick02",
  health: "Pulse01", engine: "Cpu", analysis: "Analytics01", tuning: "DashboardSpeed02",
  statements: "ChartBarIncreasing", sessions: "UserList", waits: "Hourglass", io: "ArrowUpDown",
  lock: "SquareLock01", index: "LeftToRightListBullet", table: "LayoutTable01", diagram: "HierarchySquare05",
  configuration: "SlidersHorizontal", instruments: "Cardiogram01", replication: "DatabaseSync",
  maintenance: "Tools", wrench: "Wrench01", users: "UserGroup", audit: "Audit01",
  errorlog: "OctagonAlert", warning: "Alert02", info: "InformationCircle", run: "Play",
  runAll: "FastForward", stop: "Stop", refresh: "RefreshCw", history: "History", copy: "Copy01",
  columns: "Layout3Column", inspector: "SidebarRight", "split-pane": "LayoutTwoColumn",
  browser: "SidebarLeft", view: "View", baseline: "Flag01", branches: "GitBranch",
  edit: "Edit02", trash: "Delete02", globe: "Globe", optimize: "Flash", shield: "ShieldCheck",
  minus: "MinusSign", block: "CancelCircle", clean: "BrushCleaning", undo: "Undo02",
  cluster: "Network",
};

const pkg = process.argv[2];
if (!pkg) { console.error("usage: vendor-hugeicons.mjs <extracted package dir>"); process.exit(2); }
const meta = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8"));
if (meta.name !== "@hugeicons/core-free-icons" || meta.version !== "4.3.5") {
  console.error(`expected @hugeicons/core-free-icons@4.3.5, found ${meta.name}@${meta.version}`); process.exit(2);
}
if (!/^MIT License/.test(fs.readFileSync(path.join(pkg, "LICENSE.md"), "utf8"))) { console.error("LICENSE.md is not MIT"); process.exit(2); }
const STYLE = new Set(["stroke", "strokeWidth", "strokeLinecap", "strokeLinejoin", "key"]);
let out = `// GENERATED by scripts/vendor-hugeicons.mjs. Do not edit by hand.
// Icons from @hugeicons/core-free-icons 4.3.5 (Stroke Rounded, MIT License,
// Copyright (c) 2025 Hugeicons). 24 px grid; stroke style is applied by Icon.
export type IconShape = ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>;
export const icons = {
`;
for (const [name, file] of Object.entries(MAP)) {
  const mod = await import(pathToFileURL(path.join(pkg, "dist/esm", `${file}Icon.js`)).href);
  const shape = mod.default.map(([tag, attrs]) => {
    const keep = Object.fromEntries(Object.entries(attrs).filter(([k, v]) => !STYLE.has(k) || (k === "stroke" && v !== "currentColor")));
    return [tag, keep];
  });
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(shape)}, // ${file}\n`;
}
out += `} as const satisfies Record<string, IconShape>;\n`;
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "icons.generated.ts");
fs.writeFileSync(dest, out);
console.log(`wrote ${dest} (${Object.keys(MAP).length} icons, ${out.length} bytes)`);
